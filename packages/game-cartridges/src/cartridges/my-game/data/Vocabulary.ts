const BY_DIFFICULTY_CACHE: Record<number, Record<number, WordEntry[]>> = {};

function getWordsByDifficulty(setNumber: number): Record<number, WordEntry[]> {
    if (BY_DIFFICULTY_CACHE[setNumber]) return BY_DIFFICULTY_CACHE[setNumber];

    const set = WORD_SETS[setNumber] || WORD_SETS[1];
    const result: Record<number, WordEntry[]> = {
        1: set.filter(w => w.difficulty === 1),
        2: set.filter(w => w.difficulty === 2),
        3: set.filter(w => w.difficulty === 3),
        4: set.filter(w => w.difficulty === 4),
    };
    BY_DIFFICULTY_CACHE[setNumber] = result;
    return result;
}

export function getWordSetForLevel(level: number): number {
    if (level < 5) return 1;
    if (level < 10) return 2;
    if (level < 15) return 3;
    if (level < 20) return 4;
    if (level < 25) return 5;
    return 6;
}

const activeWords = new Set<string>();

export function getRandomWord(difficulty: number, level: number = 1): string {
    const setNumber = getWordSetForLevel(level);
    const byDifficulty = getWordsByDifficulty(setNumber);
    const pool = byDifficulty[difficulty] || byDifficulty[1];
    const available = pool.filter(w => !activeWords.has(w.text));
    const source = available.length > 0 ? available : pool;
    const entry = source[Math.floor(Math.random() * source.length)];
    return entry.text;
}

export function registerActiveWord(word: string): void {
    activeWords.add(word.toLowerCase());
}

export function unregisterActiveWord(word: string): void {
    activeWords.delete(word.toLowerCase());
}

export function getWordDifficultyColor(difficulty: number): string {
    switch (difficulty) {
        case 1: return '#44ff44';
        case 2: return '#ffff44';
        case 3: return '#ff8844';
        case 4: return '#ff4444';
        default: return '#44ff44';
    }
}

